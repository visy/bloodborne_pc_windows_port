#!/usr/bin/env python3
"""Embeds data/name_filter/*.txt|tsv into the two code bases that load them without a data folder:

  scripts/namefilter_data.py              (Python: lobby service, launcher, Iosefka)
  gpu/shim/party/name_filter_data.inc     (C++: the game)

  python tools/name_filter/gen_embed.py          write both
  python tools/name_filter/gen_embed.py --check  exit 1 when they are out of date (tests/test_name_filter.py)

Run it after every edit of a data file. The data folder, when present at run time, wins over the embedded copy.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "name_filter"
FILES = ("charmap.tsv", "strict.txt", "identity.txt", "people.txt", "violence.txt", "link.txt", "codes.txt", "allow.txt")
CONST = {"charmap.tsv": "kNfCharmap", "strict.txt": "kNfStrict", "identity.txt": "kNfIdentity", "people.txt": "kNfPeople",
         "violence.txt": "kNfViolence", "link.txt": "kNfLink", "codes.txt": "kNfCodes", "allow.txt": "kNfAllow"}


def render():
    texts = {f: (DATA / f).read_text(encoding="utf-8").replace("\r\n", "\n") for f in FILES}
    py = ['"""Generated by tools/name_filter/gen_embed.py from data/name_filter/. Do not edit."""', "TEXTS = {"]
    for f in FILES:
        py.append(f"    {f!r}: {texts[f]!r},")
    py.append("}")
    cc = ["// Generated by tools/name_filter/gen_embed.py from data/name_filter/. Do not edit."]
    for f in FILES:
        assert ')NF"' not in texts[f]
        cc.append(f'static const char* const {CONST[f]} = R"NF({texts[f]})NF";')
    return "\n".join(py) + "\n", "\n".join(cc) + "\n"


def main():
    py, cc = render()
    targets = [(ROOT / "scripts" / "namefilter_data.py", py), (ROOT / "gpu" / "shim" / "party" / "name_filter_data.inc", cc)]
    if "--check" in sys.argv:
        bad = [str(p) for p, t in targets if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != t]
        if bad:
            print("out of date:", ", ".join(bad), "- run tools/name_filter/gen_embed.py")
            return 1
        return 0
    for p, t in targets:
        p.write_text(t, encoding="utf-8", newline="\n")
        print("wrote", p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
